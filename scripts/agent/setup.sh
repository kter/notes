#!/usr/bin/env bash
# Install what the CI jobs in .github/workflows/ci.yml install, so a cloud agent
# (Claude Code on the web / Codex Cloud) can run `make check` without AWS.
#
#   bash scripts/agent/setup.sh
#
# - Idempotent: tools already present at the pinned version are left alone.
# - Versions come from mise.toml (bun, uv, terraform, conftest) and
#   .python-version (Python), the same pins CI uses.
# - Tools land in .tools/bin (git-ignored). The Makefile puts that directory
#   first on PATH, so `make check` and the Claude/Codex Stop hooks find them.
# - Uses mise when it is installed; otherwise downloads from the same sources
#   CI uses (GitHub releases, releases.hashicorp.com, PyPI).
# - Needs network. On Codex Cloud run it from the environment setup script,
#   because the task phase may have no network. Terraform providers are fetched
#   here for the same reason.
# - Does NOT run `make install-hooks`: the lefthook pre-push hook runs
#   integration tests against AWS, which cloud agents must not touch.
#
# Set AGENT_SETUP_NO_MISE=1 to skip mise and use the direct downloads.

set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
cd "$ROOT"

TOOLS="$ROOT/.tools"
BIN="$TOOLS/bin"
OPT="$TOOLS/opt"
mkdir -p "$BIN" "$OPT"
export PATH="$BIN:$PATH"

log() { printf '[agent-setup] %s\n' "$*"; }
die() { printf '[agent-setup] ERROR: %s\n' "$*" >&2; exit 1; }

mise_pin() { # mise_pin <tool key as written in mise.toml>
  local v
  v=$(sed -n "s|^\"\{0,1\}$1\"\{0,1\} *= *\"\([^\"]*\)\".*|\1|p" mise.toml | head -n 1)
  [ -n "$v" ] || die "no version for $1 in mise.toml"
  printf '%s' "$v"
}

BUN_VERSION=$(mise_pin bun)
UV_VERSION=$(mise_pin uv)
TERRAFORM_VERSION=$(mise_pin terraform)
CONFTEST_VERSION=$(mise_pin 'github:open-policy-agent/conftest')
PYTHON_VERSION=$(tr -d '[:space:]' < .python-version)

case "$(uname -m)" in
  x86_64 | amd64) ARCH_BUN=x64; ARCH_GO=amd64; ARCH_CONFTEST=x86_64 ;;
  aarch64 | arm64) ARCH_BUN=aarch64; ARCH_GO=arm64; ARCH_CONFTEST=arm64 ;;
  *) die "unsupported architecture: $(uname -m)" ;;
esac

# --- caches -----------------------------------------------------------------
# Some clouds (Codex) mount $HOME read-only. Point caches into .tools when the
# default location is not writable, and record the choice in .tools/env.sh and
# .tools/env.mk so later shells and `make` reuse it.
ENV_SH="$TOOLS/env.sh"
ENV_MK="$TOOLS/env.mk"
printf '# Generated by scripts/agent/setup.sh\nexport PATH="%s:$PATH"\n' "$BIN" > "$ENV_SH"
printf '# Generated by scripts/agent/setup.sh\n' > "$ENV_MK"

writable_dir() { mkdir -p "$1" 2>/dev/null && [ -w "$1" ]; }
use_cache() { # use_cache <VAR> <default dir> <fallback dir>
  local var=$1 default=$2 fallback=$3 current
  current=${!var:-$default}
  if ! writable_dir "$current"; then
    mkdir -p "$fallback"
    export "$var=$fallback"
    printf 'export %s="%s"\n' "$var" "$fallback" >> "$ENV_SH"
    printf 'export %s := %s\n' "$var" "$fallback" >> "$ENV_MK"
    log "$current is not writable; $var=$fallback"
  fi
}
use_cache UV_CACHE_DIR "${XDG_CACHE_HOME:-$HOME/.cache}/uv" "$TOOLS/cache/uv"
use_cache UV_PYTHON_INSTALL_DIR "${XDG_DATA_HOME:-$HOME/.local/share}/uv/python" "$TOOLS/python"
use_cache BUN_INSTALL_CACHE_DIR "$HOME/.bun/install/cache" "$TOOLS/cache/bun"
use_cache npm_config_cache "$HOME/.npm" "$TOOLS/cache/npm"

# --- helpers ----------------------------------------------------------------
download() { # download <url> <dest>
  log "downloading $1"
  curl --fail --silent --show-error --location --retry 3 "$1" --output "$2" \
    || die "download failed: $1 (is this host reachable from this environment?)"
}
unzip_to() { # unzip_to <zip> <dir>
  if command -v unzip >/dev/null 2>&1; then
    unzip -q -o "$1" -d "$2"
  else
    python3 -c 'import sys, zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$1" "$2"
  fi
}
link_tool() { # link_tool <binary path> <name>
  chmod +x "$1"
  ln -sfn "$1" "$BIN/$2"
}
use_mise() { [ -z "${AGENT_SETUP_NO_MISE:-}" ] && command -v mise >/dev/null 2>&1; }
# Install one tool through mise and link it. Runs from / so an untrusted
# mise.toml in a fresh clone is never loaded (we pass the version explicitly).
mise_link() { # mise_link <mise tool> <version> <binary name>
  use_mise || return 1
  local dir
  (cd / && mise install --quiet "$1@$2") >/dev/null 2>&1 || return 1
  dir=$(cd / && mise where "$1@$2" 2>/dev/null) || return 1
  local found
  found=$(find "$dir" -maxdepth 3 -type f -name "$3" -perm -u+x 2>/dev/null | head -n 1)
  [ -n "$found" ] || return 1
  link_tool "$found" "$3"
  log "$3 $2 via mise"
}
version_of() { # version_of <command...>; prints the first x.y.z found, or nothing
  "$@" 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -n 1 || true
}

# --- uv ---------------------------------------------------------------------
if [ "$(version_of uv --version)" != "$UV_VERSION" ]; then
  if ! mise_link uv "$UV_VERSION" uv; then
    dir="$OPT/uv-$UV_VERSION"
    if [ ! -x "$dir/bin/uv" ]; then
      log "installing uv $UV_VERSION from PyPI"
      python3 -m pip install --quiet --disable-pip-version-check --no-warn-script-location \
        --target "$dir" "uv==$UV_VERSION" \
        || die "pip install uv==$UV_VERSION failed (PyPI unreachable or pip missing)"
    fi
    link_tool "$dir/bin/uv" uv
  fi
fi
log "uv: $(uv --version)"

# --- Python + backend (ci.yml: backend job) ---------------------------------
if ! uv python find "$PYTHON_VERSION" >/dev/null 2>&1; then
  log "installing Python $PYTHON_VERSION with uv"
  uv python install "$PYTHON_VERSION" \
    || die "uv python install $PYTHON_VERSION failed (needs github.com release downloads)"
fi
log "uv sync --extra dev in backend (Python $PYTHON_VERSION, same as CI)"
# backend/ has no .python-version, so pin it here; otherwise uv picks the
# newest interpreter on PATH (3.13 on Claude Code on the web).
(cd backend && uv sync --extra dev --python "$PYTHON_VERSION")

# --- bun + frontend (ci.yml: frontend job) ----------------------------------
if [ "$(version_of bun --version)" != "$BUN_VERSION" ]; then
  if ! mise_link bun "$BUN_VERSION" bun; then
    dir="$OPT/bun-$BUN_VERSION"
    if [ ! -x "$dir/bun-linux-$ARCH_BUN/bun" ]; then
      mkdir -p "$dir"
      download "https://github.com/oven-sh/bun/releases/download/bun-v$BUN_VERSION/bun-linux-$ARCH_BUN.zip" "$dir/bun.zip"
      unzip_to "$dir/bun.zip" "$dir"
      rm -f "$dir/bun.zip"
    fi
    link_tool "$dir/bun-linux-$ARCH_BUN/bun" bun
  fi
fi
log "bun: $(bun --version)"
log "bun install --frozen-lockfile in frontend"
(cd frontend && bun install --frozen-lockfile)

# --- terraform + conftest (ci.yml: terraform job) ---------------------------
if [ "$(version_of terraform version)" != "$TERRAFORM_VERSION" ]; then
  if ! mise_link terraform "$TERRAFORM_VERSION" terraform; then
    dir="$OPT/terraform-$TERRAFORM_VERSION"
    if [ ! -x "$dir/terraform" ]; then
      mkdir -p "$dir"
      download "https://releases.hashicorp.com/terraform/$TERRAFORM_VERSION/terraform_${TERRAFORM_VERSION}_linux_$ARCH_GO.zip" "$dir/terraform.zip"
      unzip_to "$dir/terraform.zip" "$dir"
      rm -f "$dir/terraform.zip"
    fi
    link_tool "$dir/terraform" terraform
  fi
fi
log "terraform: $(terraform version | head -n 1)"

if [ "$(version_of conftest --version)" != "$CONFTEST_VERSION" ]; then
  if ! mise_link github:open-policy-agent/conftest "$CONFTEST_VERSION" conftest; then
    dir="$OPT/conftest-$CONFTEST_VERSION"
    if [ ! -x "$dir/conftest" ]; then
      mkdir -p "$dir"
      download "https://github.com/open-policy-agent/conftest/releases/download/v$CONFTEST_VERSION/conftest_${CONFTEST_VERSION}_Linux_$ARCH_CONFTEST.tar.gz" "$dir/conftest.tar.gz"
      tar -xzf "$dir/conftest.tar.gz" -C "$dir" conftest
      rm -f "$dir/conftest.tar.gz"
    fi
    link_tool "$dir/conftest" conftest
  fi
fi
log "conftest: $(conftest --version | head -n 1)"

# Fetch providers now (network phase) into the data dir `make check` uses, so
# the check can run offline. Same flags as ci.yml; never touches a backend.
log "terraform init -backend=false (providers for make check)"
TF_DATA_DIR="$TOOLS/terraform-check" terraform -chdir=terraform init -backend=false -input=false >/dev/null

log "done. Run: make check"
